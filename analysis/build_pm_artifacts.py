def workdays(a: date, b: date) -> int:
    n, d = 0, a
    while d <= b:
        n += d.weekday() < 5
        d += timedelta(days=1)
    return n


# --------------------------------------------------------------------------- Excel helpers
def header(ws, row: int, values: list[str], widths: list[int] | None = None) -> None:
    for i, v in enumerate(values, 1):
        c = ws.cell(row=row, column=i, value=v)
        c.fill, c.font, c.alignment, c.border = HEAD_FILL, HEAD_FONT, WRAP, BOX
    if widths:
        for i, w in enumerate(widths, 1):
            ws.column_dimensions[get_column_letter(i)].width = w


def rows(ws, start: int, data: list[list], wrap: bool = True) -> None:
    for r, line in enumerate(data, start):
        for c, v in enumerate(line, 1):
            cell = ws.cell(row=r, column=c, value=v)
            cell.border = BOX
            if wrap:
                cell.alignment = WRAP


def title(ws, text: str, note: str = "") -> None:
    ws["A1"] = text
    ws["A1"].font = Font(bold=True, size=14, color="1F3A5F")
    if note:
        ws["A2"] = note
        ws["A2"].font = Font(italic=True, color="595959")


