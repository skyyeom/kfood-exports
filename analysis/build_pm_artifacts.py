        ("import_cagr_5y", "Import value CAGR 5y", "0.0%"), ("volume_cagr_5y", "Import volume CAGR 5y", "0.0%"),
        ("unit_price_cagr_5y", "Unit price CAGR 5y", "0.0%"), ("imports_from_kr_musd", "Imports from Korea (US$ M, partner-reported)", "#,##0.0"),
        ("kr_market_share", "Korea share of imports", "0.0%"), ("kr_exports_2025_musd", "Korea exports 2025 (US$ M, Korea-reported)", "#,##0.0"),
        ("kr_export_cagr_20_25", "Korea export CAGR 2020-25", "0.0%"), ("gdp_pc_usd", "GDP per capita (US$)", "#,##0"),
        ("population_m", "Population (M)", "#,##0.0"), ("gdp_growth_avg_21_25", "GDP growth avg 2021-25 (%)", "0.0"),
        ("lpi_score", "LPI score", "0.00"), ("hub", "Re-export hub", "@"), ("score", "Preliminary score (0-100)", "0.0"),
