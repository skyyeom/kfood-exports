def sheet_survey(wb: Workbook) -> None:
    ws = wb.create_sheet("Survey_Responses")
    meta = ["ID", "Start time", "Completion time", "Email", "Name"]
    qcols = [q[3] for q in SURVEY]
    header(ws, 1, meta + qcols, [6, 16, 16, 22, 16] + [24] * len(qcols))
    ws.freeze_panes = "B2"
    ws.cell(row=1, column=1).comment = None

    an = wb.create_sheet("Survey_Analysis")
    title(an, "Survey analysis (auto-calculated from Survey_Responses rows 2-501)",
          "Paste the Microsoft Forms 'Open in Excel' export into Survey_Responses (keep the header row). Likert answers may be text ('4') or numbers.")
    r = 4
    an.column_dimensions["A"].width = 70
    an.column_dimensions["B"].width = 16
    an.column_dimensions["C"].width = 16
    an.cell(row=r, column=1, value="Responses received").font = Font(bold=True)
    an.cell(row=r, column=2, value=f"=COUNTA(Survey_Responses!A2:A{SURVEY_ROWS + 1})").fill = CALC_FILL
    resp = f"$B${r}"
    r += 2

    likert_rows = []
    for idx, (qid, section, qtype, text, opts) in enumerate(SURVEY):
        col = get_column_letter(len(meta) + idx + 1)
        rng = f"Survey_Responses!${col}$2:${col}${SURVEY_ROWS + 1}"
        an.cell(row=r, column=1, value=f"{qid}. {text}").font = Font(bold=True)
        an.cell(row=r, column=1).alignment = WRAP
        r += 1
        if qtype in ("choice", "multi"):
            header(an, r, ["Option", "Count", "% of responses"])
            r += 1
            for o in opts:
                an.cell(row=r, column=1, value=o)
                crit = f'"*{o}*"' if qtype == "multi" else f'"{o}"'
                an.cell(row=r, column=2, value=f"=COUNTIF({rng},{crit})").fill = CALC_FILL
                c = an.cell(row=r, column=3, value=f"=IFERROR(B{r}/{resp},0)")
                c.number_format, c.fill = "0%", CALC_FILL
                r += 1
        elif qtype == "likert":
            header(an, r, ["Metric", "Value"])
            r += 1
            an.cell(row=r, column=1, value="Answers")
            an.cell(row=r, column=2, value=f"=COUNTA({rng})").fill = CALC_FILL
            n = f"B{r}"
            r += 1
            an.cell(row=r, column=1, value="Average (1-5)")
            c = an.cell(row=r, column=2, value=f'=IFERROR(SUMPRODUCT(--(LEN({rng})>0),VALUE(LEFT({rng}&"0",1)))/{n},"")')
            c.number_format, c.fill = "0.00", CALC_FILL
            avg = f"B{r}"
            r += 1
            an.cell(row=r, column=1, value="Top-2-box (% answering 4 or 5)")
            c = an.cell(row=r, column=2, value=f'=IFERROR(SUMPRODUCT(--(LEN({rng})>0),--(VALUE(LEFT({rng}&"0",1))>=4))/{n},"")')
            c.number_format, c.fill = "0%", CALC_FILL
            likert_rows.append((qid, text, section, avg, f"B{r}"))
            r += 1
        else:
            an.cell(row=r, column=1, value="Free text — code answers in Insight_Synthesis.").font = Font(italic=True)
            r += 1
        r += 1

    an.cell(row=r, column=1, value="Summary: pains and features ranked by average score").font = Font(bold=True, size=12)
    r += 1
    header(an, r, ["Question", "Section", "Average", "Top-2-box", "Rank within section"])
    an.column_dimensions["D"].width = 14
    an.column_dimensions["E"].width = 18
    start = r + 1
    for i, (qid, text, section, avg, t2b) in enumerate(likert_rows):
        rr = start + i
        an.cell(row=rr, column=1, value=f"{qid}. {text}").alignment = WRAP
        an.cell(row=rr, column=2, value=section)
        c = an.cell(row=rr, column=3, value=f"={avg}")
        c.number_format, c.fill = "0.00", CALC_FILL
        c = an.cell(row=rr, column=4, value=f"={t2b}")
        c.number_format, c.fill = "0%", CALC_FILL
    end = start + len(likert_rows) - 1
    for rr in range(start, end + 1):
        c = an.cell(row=rr, column=5,
                    value=f'=IF(C{rr}="","",COUNTIFS($B${start}:$B${end},B{rr},$C${start}:$C${end},">"&C{rr})+1)')
        c.fill = CALC_FILL


