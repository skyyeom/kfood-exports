def sheet_tam(wb: Workbook) -> None:
    ws = wb.create_sheet("TAM_SAM_SOM")
    title(ws, "Market sizing (HS 1704+1806+1905+2105 imports, latest year, US$ M)",
          "Edit 'In SAM?' (Y/N) and the SOM share-gain inputs. TAM excludes nothing; adjusted TAM excludes hubs, RUS, MMR.")
    m = pd.read_csv(OUT / "t3_destination_markets.csv", index_col=0)
    sam = {"USA", "CAN", "PHL", "MYS", "THA", "VNM", "IDN", "KHM", "IND", "KAZ", "MNG", "SAU"}
    excl = {"HKG", "SGP", "NLD", "ARE", "RUS", "MMR"}
    header(ws, 4, ["ISO3", "Category imports", "Imports from Korea", "In SAM? (Y/N)", "Excluded from adj. TAM? (Y/N)",
                   "Bakery & biscuits", "Chocolate", "Sugar confectionery", "Ice cream"], [8, 16, 16, 14, 18, 16, 14, 18, 12])
    r = 5
    for iso, row in m.sort_values("imports_latest_musd", ascending=False).iterrows():
        vals = [iso, row.imports_latest_musd, None if pd.isna(row.imports_from_kr_musd) else row.imports_from_kr_musd,
                "Y" if iso in sam else "N", "Y" if iso in excl else "N",
                row["imp_Bakery & biscuits"], row["imp_Chocolate"], row["imp_Sugar confectionery"], row["imp_Ice cream"]]
        for j, v in enumerate(vals, 1):
            c = ws.cell(row=r, column=j, value=v)
            c.border = BOX
            if j in (2, 3, 6, 7, 8, 9):
                c.number_format = "#,##0.0"
            if j in (4, 5):
                c.fill = INPUT_FILL
        r += 1
    last = r - 1
    dv = DataValidation(type="list", formula1='"Y,N"', allow_blank=False)
    ws.add_data_validation(dv)
    dv.add(f"D5:E{last}")
    s = last + 2
    B, C, D, E = (f"{x}5:{x}{last}" for x in "BCDE")
    summary = [
        ("TAM (all candidate reporters)", f"=SUM({B})", "#,##0.0"),
        ("Adjusted TAM (excl. hubs, RUS, MMR)", f'=SUMIF({E},"N",{B})', "#,##0.0"),
        ("SAM (In SAM = Y)", f'=SUMIF({D},"Y",{B})', "#,##0.0"),
        ("Imports from Korea within SAM", f'=SUMIF({D},"Y",{C})', "#,##0.0"),
        ("Korea share of SAM", f"=B{s + 3}/B{s + 2}", "0.00%"),
        ("SAM — bakery & biscuits", f'=SUMIF({D},"Y",F5:F{last})', "#,##0.0"),
        ("SAM — chocolate", f'=SUMIF({D},"Y",G5:G{last})', "#,##0.0"),
        ("SAM — sugar confectionery", f'=SUMIF({D},"Y",H5:H{last})', "#,##0.0"),
        ("SAM — ice cream", f'=SUMIF({D},"Y",I5:I{last})', "#,##0.0"),
    ]
    for i, (label, f, fmt) in enumerate(summary):
        ws.cell(row=s + i, column=1, value=label).font = Font(bold=True)
        c = ws.cell(row=s + i, column=2, value=f)
        c.number_format, c.fill = fmt, CALC_FILL
    t = s + len(summary) + 1
    ws.cell(row=t, column=1, value="SOM scenarios (illustrative)").font = Font(bold=True, size=12)
    header(ws, t + 1, ["Scenario", "Share gain (pp of SAM)", "SOM (US$ M)", "SOM (₩ bn)"])
    ws.cell(row=t + 5, column=1, value="KRW per US$ (assumption)")
    fx = ws.cell(row=t + 5, column=2, value=1400)
    fx.fill = INPUT_FILL
    for i, (name, pp) in enumerate([("Conservative", 0.001), ("Base", 0.0025), ("Ambitious", 0.005)]):
        rr = t + 2 + i
        ws.cell(row=rr, column=1, value=name)
        c = ws.cell(row=rr, column=2, value=pp)
        c.number_format, c.fill = "0.00%", INPUT_FILL
        c = ws.cell(row=rr, column=3, value=f"=B{rr}*$B${s + 2}")
        c.number_format, c.fill = "#,##0.0", CALC_FILL
        c = ws.cell(row=rr, column=4, value=f"=C{rr}*$B${t + 5}/1000")
        c.number_format, c.fill = "#,##0.0", CALC_FILL
    ws.column_dimensions["A"].width = 38


