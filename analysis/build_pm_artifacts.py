def sheet_roadmap(wb: Workbook) -> None:
    ws = wb.create_sheet("Roadmap")
    title(ws, "High-level roadmap (anticipated windows; re-baseline to the official challenge schedule)")
    cols = ["ID", "Release / milestone", "Horizon", "Theme", "Start", "Finish", "Client objective"]
    months = []
    m = date(2026, 10, 1)
    while m <= date(2028, 12, 1):
        months.append(m)
        m = date(m.year + (m.month // 12), m.month % 12 + 1, 1)
    header(ws, 4, cols + [mm.strftime("%y-%m") for mm in months], [6, 58, 8, 14, 11, 11, 30] + [5] * len(months))
    for i, (tid, name, hz, theme, s, f, ms, _, obj, _) in enumerate(ROADMAP, 5):
        vals = [tid, name, hz, theme, s, f, obj]
        for j, v in enumerate(vals, 1):
            c = ws.cell(row=i, column=j, value=v)
            c.border = BOX
            if j in (5, 6):
                c.number_format = "yyyy-mm-dd"
            if theme == "Summary":
                c.font = Font(bold=True)
    # month header dates (hidden helper row 3) for formula-driven Gantt
    for k, mm in enumerate(months):
        col = 8 + k
        ws.cell(row=3, column=col, value=mm).number_format = "yyyy-mm-dd"
    ws.row_dimensions[3].hidden = True
    last = 4 + len(ROADMAP)
    first_col, last_col = get_column_letter(8), get_column_letter(7 + len(months))
    rng = f"{first_col}5:{last_col}{last}"
    ws.conditional_formatting.add(rng, FormulaRule(
        formula=[f'AND($D5="Milestone",$E5>={first_col}$3,$E5<EDATE({first_col}$3,1))'], fill=PatternFill("solid", fgColor="C00000")))
    ws.conditional_formatting.add(rng, FormulaRule(
        formula=[f'AND($D5="Client objective",$E5>={first_col}$3,$E5<EDATE({first_col}$3,1))'], fill=PatternFill("solid", fgColor="7030A0")))
    ws.conditional_formatting.add(rng, FormulaRule(
        formula=[f'AND($D5="Summary",$E5<EDATE({first_col}$3,1),$F5>={first_col}$3)'], fill=PatternFill("solid", fgColor="808080")))
    ws.conditional_formatting.add(rng, FormulaRule(
        formula=[f'AND($E5<EDATE({first_col}$3,1),$F5>={first_col}$3)'], fill=PatternFill("solid", fgColor="2E75B6")))
    ws.freeze_panes = "H5"


