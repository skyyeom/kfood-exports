# --------------------------------------------------------------------------- MS Project (MSPDI XML + CSV)
def build_msproject() -> tuple[Path, Path]:
    ns = "http://schemas.microsoft.com/project"
    ET.register_namespace("", ns)
    proj = ET.Element(f"{{{ns}}}Project")

    def sub(parent, tag, text=None):
        e = ET.SubElement(parent, f"{{{ns}}}{tag}")
        if text is not None:
            e.text = str(text)
        return e

    sub(proj, "Name", "WellGTM_Roadmap.xml")
    sub(proj, "Title", "WellGTM high-level product roadmap")
    sub(proj, "ScheduleFromStart", 1)
    sub(proj, "StartDate", "2026-10-26T08:00:00")
    sub(proj, "MinutesPerDay", 480)
    sub(proj, "MinutesPerWeek", 2400)
    sub(proj, "DaysPerMonth", 20)
    tasks = sub(proj, "Tasks")
    uid = {t[0]: i for i, t in enumerate(ROADMAP, 1)}
    outline_parent = None
    n1 = n2 = 0
    for i, (tid, name, hz, theme, s, f, ms, preds, obj, pct) in enumerate(ROADMAP, 1):
        is_sum = theme == "Summary"
        if is_sum:
            n1 += 1
            n2 = 0
            outline_parent = n1
            outline, level = str(n1), 1
        else:
            n2 += 1
            outline, level = f"{outline_parent}.{n2}", 2
        t = sub(tasks, "Task")
        sub(t, "UID", i)
        sub(t, "ID", i)
        sub(t, "Name", name.replace("◆ ", ""))
        sub(t, "Type", 1)
        sub(t, "IsNull", 0)
        sub(t, "WBS", outline)
        sub(t, "OutlineNumber", outline)
        sub(t, "OutlineLevel", level)
        sub(t, "Priority", 500)
        sub(t, "Start", f"{s.isoformat()}T08:00:00")
        sub(t, "Finish", f"{f.isoformat()}T{'08' if ms else '17'}:00:00")
        hours = 0 if ms else workdays(s, f) * 8
        sub(t, "Duration", f"PT{hours}H0M0S")
        sub(t, "DurationFormat", 7)
        sub(t, "Milestone", int(ms))
        sub(t, "Summary", int(is_sum))
        sub(t, "PercentComplete", pct or 0)
        if not is_sum:
            sub(t, "ConstraintType", 4)  # Start No Earlier Than: keeps anticipated dates
            sub(t, "ConstraintDate", f"{s.isoformat()}T08:00:00")
        note = f"Horizon: {hz}; Theme: {theme}" + (f"; Client objective: {obj}" if obj else "")
        sub(t, "Notes", note)
        for p in preds:
            pl = sub(t, "PredecessorLink")
            sub(pl, "PredecessorUID", uid[p])
            sub(pl, "Type", 1)  # finish-to-start
    xml_path = WB_DIR / "WellGTM_roadmap_MSProject.xml"
    ET.ElementTree(proj).write(xml_path, encoding="utf-8", xml_declaration=True)

    csv_path = WB_DIR / "WellGTM_roadmap_MSProject_import.csv"
    with csv_path.open("w", newline="", encoding="utf-8-sig") as fh:
        w = csv.writer(fh)
        w.writerow(["ID", "Name", "Outline Level", "Start", "Finish", "Duration", "Milestone", "Predecessors", "% Complete", "Notes"])
        for i, (tid, name, hz, theme, s, f, ms, preds, obj, pct) in enumerate(ROADMAP, 1):
            level = 1 if theme == "Summary" else 2
            dur = "0 days" if ms else f"{workdays(s, f)} days"
            w.writerow([i, name.replace("◆ ", ""), level, s.isoformat(), f.isoformat(), dur, "Yes" if ms else "No",
                        ";".join(str(uid[p]) for p in preds), pct or 0, f"{hz} · {theme}" + (f" · {obj}" if obj else "")])
    return xml_path, csv_path


# --------------------------------------------------------------------------- Gantt PNG
def build_gantt() -> Path:
    from matplotlib import font_manager

    installed = {f.name for f in font_manager.fontManager.ttflist}
    korean = [f for f in ("Apple SD Gothic Neo", "AppleGothic", "Malgun Gothic", "NanumGothic", "Noto Sans CJK KR") if f in installed]
    if korean:
        plt.rcParams["font.family"] = [korean[0], "DejaVu Sans"]
    colors = {"Product": "#7F7F7F", "Data": "#2E75B6", "Intelligence": "#548235", "Experience": "#BF8F00",
              "AI agent": "#C55A11", "Monitoring": "#7030A0", "Platform": "#1F3A5F", "GTM": "#00B0F0"}
    items = [t for t in ROADMAP]
    fig, ax = plt.subplots(figsize=(13, 8))
    for y, (tid, name, hz, theme, s, f, ms, *_rest) in enumerate(items):
        yy = len(items) - y
        if theme == "Summary":
            ax.barh(yy, (f - s).days + 1, left=mdates.date2num(s), height=0.35, color="#D9D9D9", edgecolor="#595959")
            ax.text(mdates.date2num(s), yy + 0.35, name, fontsize=9, fontweight="bold", va="bottom")
        elif ms:
            ax.scatter(mdates.date2num(s), yy, marker="D", s=70,
                       color="#7030A0" if theme == "Client objective" else "#C00000", zorder=3)
            ax.text(mdates.date2num(s) + 6, yy, name.replace("◆ ", ""), fontsize=8, va="center")
        else:
            ax.barh(yy, max((f - s).days, 3), left=mdates.date2num(s), height=0.6, color=colors.get(theme, "#999"))
            ax.text(mdates.date2num(f) + 6, yy, name, fontsize=8, va="center")
    today = date(2026, 10, 29)
    ax.axvline(mdates.date2num(today), color="red", ls="--", lw=1)
    ax.text(mdates.date2num(today), len(items) + 1.2, "today", color="red", fontsize=8, ha="center")
    ax.xaxis_date()
    ax.xaxis.set_major_locator(mdates.MonthLocator(bymonth=[1, 4, 7, 10]))
    ax.xaxis.set_major_formatter(mdates.DateFormatter("%b %Y"))
    ax.set_xlim(mdates.date2num(date(2026, 10, 1)), mdates.date2num(date(2029, 6, 30)))
    ax.set_yticks([])
    ax.set_ylim(0, len(items) + 2)
    ax.grid(axis="x", alpha=0.3)
    ax.set_title("WellGTM high-level roadmap (anticipated; re-baseline to official challenge dates)")
    handles = [plt.Rectangle((0, 0), 1, 1, color=c) for c in colors.values()]
    ax.legend(handles, colors.keys(), loc="lower left", fontsize=8, ncol=4)
    plt.tight_layout()
    path = FIG / "roadmap_gantt.png"
    plt.savefig(path, dpi=150)
    plt.close()
    return path


